#!/usr/bin/env bash
# Writes the Homebrew formula and the Scoop manifest for one CLI release.
# Usage: scripts/render.sh <version without "v"> <directory with the release binaries>
set -euo pipefail

version="$1"
assets="$2"
repo="https://github.com/Chili-Piper/homebrew-tap"
base="$repo/releases/download/v$version"

sha() { sha256sum "$assets/$1" | cut -d' ' -f1; }

mac_sha=$(sha chili-piper-cli.macos-arm64)
linux_sha=$(sha chili-piper-cli.linux-x86_64)
win_sha=$(sha chili-piper-cli.windows-x86_64.exe)

root=$(cd "$(dirname "$0")/.." && pwd)
mkdir -p "$root/Formula" "$root/bucket"

cat > "$root/Formula/chili-piper-cli.rb" <<EOF
# Generated by scripts/render.sh. Do not edit by hand.
class ChiliPiperCli < Formula
  desc "Command-line client for the Chili Piper Edge API"
  homepage "$repo"
  version "$version"
  license :cannot_represent

  on_macos do
    on_arm do
      url "$base/chili-piper-cli.macos-arm64"
      sha256 "$mac_sha"
    end
  end

  on_linux do
    on_intel do
      url "$base/chili-piper-cli.linux-x86_64"
      sha256 "$linux_sha"
    end
  end

  def install
    bin.install Dir["chili-piper-cli.*"].first => "chili-piper-cli"
  end

  test do
    system bin/"chili-piper-cli", "--help"
  end
end
EOF

cat > "$root/bucket/chili-piper-cli.json" <<EOF
{
  "version": "$version",
  "description": "Command-line client for the Chili Piper Edge API",
  "homepage": "$repo",
  "license": {
    "identifier": "Proprietary",
    "url": "$repo/blob/main/TERMS.md"
  },
  "architecture": {
    "64bit": {
      "url": "$base/chili-piper-cli.windows-x86_64.exe#/chili-piper-cli.exe",
      "hash": "$win_sha"
    }
  },
  "bin": "chili-piper-cli.exe",
  "checkver": {
    "github": "$repo"
  },
  "autoupdate": {
    "architecture": {
      "64bit": {
        "url": "$repo/releases/download/v\$version/chili-piper-cli.windows-x86_64.exe#/chili-piper-cli.exe"
      }
    }
  }
}
EOF
